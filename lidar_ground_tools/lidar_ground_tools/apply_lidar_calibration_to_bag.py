#!/usr/bin/env python3
"""
Apply lidar_ground_calibration.yaml to a ROS2 PointCloud2 bag.

The script reads an input rosbag2 directory, transforms only the x/y/z fields
of PointCloud2 messages, preserves all other point fields, and writes a new bag.
"""

import argparse
import math
import shutil
from pathlib import Path
from typing import Dict, Optional

import numpy as np
import yaml

import rosbag2_py
from rclpy.serialization import deserialize_message, serialize_message
from rosidl_runtime_py.utilities import get_message
from sensor_msgs.msg import PointCloud2
from sensor_msgs_py import point_cloud2


def parse_args() -> argparse.Namespace:
    here = Path.cwd()
    parser = argparse.ArgumentParser(
        description='Apply LiDAR extrinsic calibration YAML to a PointCloud2 rosbag2 bag.'
    )
    parser.add_argument(
        '--input-bag',
        default=str(here / 'pcd_bag'),
        help='Input rosbag2 directory.',
    )
    parser.add_argument(
        '--output-bag',
        default=str(here / 'pcd_bag_calibrated'),
        help='Output rosbag2 directory. Must not exist unless --overwrite is used.',
    )
    parser.add_argument(
        '--calibration-yaml',
        default=str(here / 'lidar_ground_calibration.yaml'),
        help='YAML generated by calibrate_lidar_ground_once.py.',
    )
    parser.add_argument(
        '--topic',
        default='/pcd_pointcloud',
        help='Input PointCloud2 topic to transform.',
    )
    parser.add_argument(
        '--output-topic',
        default=None,
        help='Output topic name. Default keeps the input topic name.',
    )
    parser.add_argument(
        '--output-frame',
        default=None,
        help='Output header.frame_id. Default uses lidar_extrinsic.parent_frame from YAML.',
    )
    parser.add_argument(
        '--keep-frame-id',
        action='store_true',
        help='Keep original PointCloud2 header.frame_id instead of setting --output-frame.',
    )
    parser.add_argument(
        '--copy-other-topics',
        action='store_true',
        help='Copy non-target topics without modification.',
    )
    parser.add_argument(
        '--overwrite',
        action='store_true',
        help='Remove output bag directory first if it already exists.',
    )
    return parser.parse_args()


def rotation_matrix_rpy(roll: float, pitch: float, yaw: float) -> np.ndarray:
    cr, sr = math.cos(roll), math.sin(roll)
    cp, sp = math.cos(pitch), math.sin(pitch)
    cy, sy = math.cos(yaw), math.sin(yaw)
    rx = np.array([[1.0, 0.0, 0.0], [0.0, cr, -sr], [0.0, sr, cr]], dtype=np.float64)
    ry = np.array([[cp, 0.0, sp], [0.0, 1.0, 0.0], [-sp, 0.0, cp]], dtype=np.float64)
    rz = np.array([[cy, -sy, 0.0], [sy, cy, 0.0], [0.0, 0.0, 1.0]], dtype=np.float64)
    return rz @ ry @ rx


def load_transform(calibration_yaml: Path):
    with calibration_yaml.open('r', encoding='utf-8') as f:
        root = yaml.safe_load(f)
    extrinsic = root['lidar_extrinsic']
    rotation = rotation_matrix_rpy(
        float(extrinsic['roll']),
        float(extrinsic['pitch']),
        float(extrinsic['yaw']),
    )
    translation = np.array(
        [float(extrinsic['x']), float(extrinsic['y']), float(extrinsic['z'])],
        dtype=np.float64,
    )
    parent_frame = str(extrinsic.get('parent_frame', 'map'))
    child_frame = str(extrinsic.get('child_frame', 'lidar'))
    return rotation, translation, parent_frame, child_frame, extrinsic


def topic_metadata_to_dict(reader) -> Dict[str, rosbag2_py.TopicMetadata]:
    return {topic.name: topic for topic in reader.get_all_topics_and_types()}


def pointcloud_row_views(msg: PointCloud2, mutable_data: bytearray):
    dtype = point_cloud2.dtype_from_fields(msg.fields, msg.point_step)
    expected_tight_row_step = msg.point_step * msg.width

    if msg.row_step == expected_tight_row_step:
        return [
            np.ndarray(
                shape=(msg.width * msg.height,),
                dtype=dtype,
                buffer=mutable_data,
            )
        ]

    return [
        np.ndarray(
            shape=(msg.width,),
            dtype=dtype,
            buffer=mutable_data,
            offset=row * msg.row_step,
            strides=(msg.point_step,),
        )
        for row in range(msg.height)
    ]


def transform_pointcloud2(
    msg: PointCloud2,
    rotation: np.ndarray,
    translation: np.ndarray,
    output_frame: Optional[str],
) -> PointCloud2:
    field_names = {field.name for field in msg.fields}
    missing = {'x', 'y', 'z'} - field_names
    if missing:
        raise ValueError(f'PointCloud2 is missing required fields: {sorted(missing)}')

    mutable_data = bytearray(msg.data)
    for cloud in pointcloud_row_views(msg, mutable_data):
        x = cloud['x'].astype(np.float64, copy=False)
        y = cloud['y'].astype(np.float64, copy=False)
        z = cloud['z'].astype(np.float64, copy=False)
        finite = np.isfinite(x) & np.isfinite(y) & np.isfinite(z)
        if not finite.any():
            continue

        xyz = np.column_stack([x[finite], y[finite], z[finite]])
        transformed = xyz @ rotation.T + translation

        cloud['x'][finite] = transformed[:, 0].astype(cloud['x'].dtype, copy=False)
        cloud['y'][finite] = transformed[:, 1].astype(cloud['y'].dtype, copy=False)
        cloud['z'][finite] = transformed[:, 2].astype(cloud['z'].dtype, copy=False)

    msg.data = bytes(mutable_data)
    if output_frame is not None:
        msg.header.frame_id = output_frame
    return msg


def open_reader(input_bag: Path):
    reader = rosbag2_py.SequentialReader()
    reader.open(
        rosbag2_py.StorageOptions(uri=str(input_bag), storage_id='sqlite3'),
        rosbag2_py.ConverterOptions(input_serialization_format='cdr', output_serialization_format='cdr'),
    )
    return reader


def open_writer(output_bag: Path):
    writer = rosbag2_py.SequentialWriter()
    writer.open(
        rosbag2_py.StorageOptions(uri=str(output_bag), storage_id='sqlite3'),
        rosbag2_py.ConverterOptions(input_serialization_format='cdr', output_serialization_format='cdr'),
    )
    return writer


def main() -> int:
    args = parse_args()
    input_bag = Path(args.input_bag).expanduser().resolve()
    output_bag = Path(args.output_bag).expanduser().resolve()
    calibration_yaml = Path(args.calibration_yaml).expanduser().resolve()
    output_topic = args.output_topic or args.topic

    if not input_bag.exists():
        raise FileNotFoundError(f'Input bag does not exist: {input_bag}')
    if not calibration_yaml.exists():
        raise FileNotFoundError(f'Calibration YAML does not exist: {calibration_yaml}')
    if output_bag.exists():
        if not args.overwrite:
            raise FileExistsError(f'Output bag already exists: {output_bag} (use --overwrite)')
        shutil.rmtree(output_bag)

    rotation, translation, parent_frame, child_frame, extrinsic = load_transform(calibration_yaml)
    output_frame = None if args.keep_frame_id else (args.output_frame or parent_frame)

    reader = open_reader(input_bag)
    topics = topic_metadata_to_dict(reader)
    if args.topic not in topics:
        available = ', '.join(sorted(topics))
        raise ValueError(f'Topic {args.topic!r} not found. Available topics: {available}')
    if topics[args.topic].type != 'sensor_msgs/msg/PointCloud2':
        raise TypeError(f'Topic {args.topic!r} is {topics[args.topic].type}, not PointCloud2')

    writer = open_writer(output_bag)

    created_topics = set()
    for name, metadata in topics.items():
        if name == args.topic:
            writer.create_topic(
                rosbag2_py.TopicMetadata(
                    name=output_topic,
                    type='sensor_msgs/msg/PointCloud2',
                    serialization_format=metadata.serialization_format,
                    offered_qos_profiles=metadata.offered_qos_profiles,
                )
            )
            created_topics.add(name)
        elif args.copy_other_topics:
            writer.create_topic(metadata)
            created_topics.add(name)

    type_cache = {
        name: get_message(metadata.type)
        for name, metadata in topics.items()
        if name != args.topic and args.copy_other_topics
    }

    transformed_count = 0
    copied_count = 0
    skipped_count = 0
    first_stamp = None
    last_stamp = None

    while reader.has_next():
        topic_name, serialized, timestamp = reader.read_next()
        if first_stamp is None:
            first_stamp = timestamp
        last_stamp = timestamp

        if topic_name == args.topic:
            msg = deserialize_message(serialized, PointCloud2)
            msg = transform_pointcloud2(msg, rotation, translation, output_frame)
            writer.write(output_topic, serialize_message(msg), timestamp)
            transformed_count += 1
        elif args.copy_other_topics and topic_name in created_topics:
            msg_type = type_cache[topic_name]
            msg = deserialize_message(serialized, msg_type)
            writer.write(topic_name, serialize_message(msg), timestamp)
            copied_count += 1
        else:
            skipped_count += 1

    print('')
    print('========== Apply LiDAR Calibration To Bag ==========')
    print(f'input_bag:          {input_bag}')
    print(f'output_bag:         {output_bag}')
    print(f'calibration_yaml:   {calibration_yaml}')
    print(f'input_topic:        {args.topic}')
    print(f'output_topic:       {output_topic}')
    print(f'output_frame_id:    {output_frame if output_frame is not None else "kept from input"}')
    print(f'parent_frame_yaml:  {parent_frame}')
    print(f'child_frame_yaml:   {child_frame}')
    print(f'x y z:              {translation[0]:.6f}, {translation[1]:.6f}, {translation[2]:.6f}')
    print(
        'roll pitch yaw deg: '
        f'{float(extrinsic["roll_deg"]):.6f}, '
        f'{float(extrinsic["pitch_deg"]):.6f}, '
        f'{float(extrinsic["yaw_deg"]):.6f}'
    )
    print(f'transformed_msgs:   {transformed_count}')
    print(f'copied_msgs:        {copied_count}')
    print(f'skipped_msgs:       {skipped_count}')
    if first_stamp is not None:
        print(f'time_range_ns:      {first_stamp} -> {last_stamp}')
    print('====================================================')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

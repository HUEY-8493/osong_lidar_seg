#!/usr/bin/env bash
set -euo pipefail

# ============================================================
# Guardian AI Manager systemd installer
#
# Expected directory:
#
#   scripts/
#   ├── guardian_manager.py
#   ├── cx128s2_control.py
#   ├── mobile_crane_status.py
#   ├── run_lidar.sh
#   └── setup_guardian_manager_service.sh
#
# Run:
#   sudo ./setup_guardian_manager_service.sh crane
#   sudo ./setup_guardian_manager_service.sh general
#   sudo ./setup_guardian_manager_service.sh crane          # update existing mode
#   sudo ./setup_guardian_manager_service.sh --force crane  # replace existing service
# ============================================================

usage() {
    echo "Usage: sudo $0 [--force] [crane|general]" >&2
    exit 2
}

SYSTEM_MODE=""
FORCE_REINSTALL=false
MODE_EXPLICIT=false
for arg in "$@"; do
    case "$arg" in
        crane|general)
            [ -z "$SYSTEM_MODE" ] || usage
            SYSTEM_MODE="$arg"
            MODE_EXPLICIT=true
            ;;
        --force) FORCE_REINSTALL=true ;;
        *) usage ;;
    esac
done
SYSTEM_MODE="${SYSTEM_MODE:-general}"

SERVICE_NAME="guardian-manager.service"
SERVICE_PATH="/etc/systemd/system/${SERVICE_NAME}"

# ------------------------------------------------------------
# Root check
# ------------------------------------------------------------

if [ "$(id -u)" -ne 0 ]; then
    echo "[ERROR] This installer must be run with sudo."
    echo
    echo "  sudo $0"
    echo
    exit 1
fi

# Check systemd too, because a unit may live outside /etc/systemd/system.
SERVICE_EXISTS=false
if [ -e "$SERVICE_PATH" ] || [ -L "$SERVICE_PATH" ] || systemctl cat "$SERVICE_NAME" >/dev/null 2>&1; then
    SERVICE_EXISTS=true
fi

# ------------------------------------------------------------
# Detect real user
#
# sudo ./script.sh
# -> SUDO_USER = actual desktop user
# ------------------------------------------------------------

if [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != "root" ]; then
    TARGET_USER="$SUDO_USER"
else
    TARGET_USER="$(logname 2>/dev/null || true)"
fi

if [ -z "${TARGET_USER:-}" ] || [ "$TARGET_USER" = "root" ]; then
    echo "[ERROR] Could not determine the desktop user."
    echo "[ERROR] Run this script from the normal user session using sudo."
    exit 1
fi

TARGET_UID="$(id -u "$TARGET_USER")"
TARGET_HOME="$(getent passwd "$TARGET_USER" | cut -d: -f6)"

if [ -z "$TARGET_HOME" ]; then
    echo "[ERROR] Could not determine home directory for: $TARGET_USER"
    exit 1
fi

# ------------------------------------------------------------
# Paths
# ------------------------------------------------------------

# Directory containing this installer
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

# Runtime Python sources must exist beside this installer.
SOURCE_MANAGER="${SCRIPT_DIR}/guardian_manager.py"
SOURCE_CONTROLLER="${SCRIPT_DIR}/cx128s2_control.py"
SOURCE_CRANE_STATUS="${SCRIPT_DIR}/mobile_crane_status.py"
SOURCE_RUN_LIDAR="${SCRIPT_DIR}/run_lidar.sh"

# Runtime/service directory
WORK_DIR="${TARGET_HOME}/docker/ros2_jazzy"
MANAGER_PATH="${WORK_DIR}/guardian_manager.py"
CONTROLLER_PATH="${WORK_DIR}/cx128s2_control.py"
CRANE_STATUS_PATH="${WORK_DIR}/mobile_crane_status.py"
RUN_LIDAR_PATH="${WORK_DIR}/run_lidar.sh"

# Runtime wrapper generated by this installer
START_WRAPPER="${WORK_DIR}/start_guardian_manager.sh"

# ------------------------------------------------------------
# GUI environment
# ------------------------------------------------------------

DISPLAY_VALUE=":0"
XDG_RUNTIME_DIR_VALUE="/run/user/${TARGET_UID}"
XAUTHORITY_VALUE="${XDG_RUNTIME_DIR_VALUE}/gdm/Xauthority"

echo
echo "============================================================"
echo " Guardian AI Manager Service Installer"
echo "============================================================"
echo
echo "[INFO] User           : $TARGET_USER"
echo "[INFO] UID            : $TARGET_UID"
echo "[INFO] Home           : $TARGET_HOME"
echo "[INFO] Source manager : $SOURCE_MANAGER"
echo "[INFO] Work directory : $WORK_DIR"
if [ "$SERVICE_EXISTS" = true ] && [ "$MODE_EXPLICIT" = false ]; then
    echo "[INFO] System mode    : preserve existing startup mode (no explicit mode requested)"
else
    echo "[INFO] System mode    : $SYSTEM_MODE"
fi
echo "[INFO] DISPLAY        : $DISPLAY_VALUE"
echo "[INFO] XAUTHORITY     : $XAUTHORITY_VALUE"
echo "[INFO] Runtime dir    : $XDG_RUNTIME_DIR_VALUE"
echo

# ------------------------------------------------------------
# Check source guardian_manager.py
# ------------------------------------------------------------

if [ ! -f "$SOURCE_MANAGER" ]; then
    echo "[ERROR] guardian_manager.py not found."
    echo
    echo "Expected:"
    echo "  $SOURCE_MANAGER"
    echo
    echo "Place guardian_manager.py in the same directory as:"
    echo "  $(basename "$0")"
    exit 1
fi

if [ ! -f "$SOURCE_CONTROLLER" ]; then
    echo "[ERROR] cx128s2_control.py not found beside guardian_manager.py."
    exit 1
fi

if [ ! -f "$SOURCE_CRANE_STATUS" ]; then
    echo "[ERROR] mobile_crane_status.py not found beside guardian_manager.py."
    exit 1
fi

if [ ! -f "$SOURCE_RUN_LIDAR" ]; then
    echo "[ERROR] run_lidar.sh not found beside guardian_manager.py." >&2
    exit 1
fi

if [ "$SERVICE_EXISTS" = true ] && [ "$FORCE_REINSTALL" = false ] && [ ! -f "$START_WRAPPER" ]; then
    echo "[ERROR] Existing service has no expected startup wrapper: $START_WRAPPER" >&2
    echo "[ERROR] Use --force to replace the service configuration." >&2
    exit 1
fi

# ------------------------------------------------------------
# Create work directory
# ------------------------------------------------------------

echo "[INFO] Creating runtime directory..."

mkdir -p "$WORK_DIR"

# ------------------------------------------------------------
# Copy manager
# ------------------------------------------------------------

echo "[INFO] Copying Guardian Manager Python sources..."

SOURCE_CHANGED=false
copy_if_changed() {
    if ! cmp -s "$1" "$2"; then
        if [ -f "$2" ] && [ ! -e "$2.setup-backup" ]; then cp -p "$2" "$2.setup-backup"; fi
        cp -f "$1" "$2"
        SOURCE_CHANGED=true
    fi
}

copy_if_changed "$SOURCE_MANAGER" "$MANAGER_PATH"
copy_if_changed "$SOURCE_CONTROLLER" "$CONTROLLER_PATH"
copy_if_changed "$SOURCE_CRANE_STATUS" "$CRANE_STATUS_PATH"
copy_if_changed "$SOURCE_RUN_LIDAR" "$RUN_LIDAR_PATH"

chmod 755 "$MANAGER_PATH" "$CONTROLLER_PATH" "$CRANE_STATUS_PATH" "$RUN_LIDAR_PATH"

echo "[INFO] Installed manager:"
echo "       $SOURCE_MANAGER"
echo "       -> $MANAGER_PATH"

if [ "$SERVICE_EXISTS" = true ] && [ "$FORCE_REINSTALL" = false ]; then
    if [ "$MODE_EXPLICIT" = true ]; then
        # Preserve the service unit, GUI environment and local wrapper additions.
        # Only replace the known Manager exec command when a mode was requested.
        MODE_CHANGED=$(python3 - "$START_WRAPPER" "$SYSTEM_MODE" <<'PYMODE'
from pathlib import Path
import shlex
import shutil
import sys
path, mode = Path(sys.argv[1]), sys.argv[2]
text = path.read_text()
lines = text.splitlines(keepends=True)
matches = []
for index, line in enumerate(lines):
    try:
        words = shlex.split(line)
    except ValueError:
        continue
    if words[:3] == ["exec", "/usr/bin/python3", "$MANAGER_PATH"]:
        if words[3:] not in ([], ["crane"], ["general"], ["--mode", "crane"], ["--mode", "general"]):
            raise SystemExit("Unrecognized Manager arguments; wrapper was not changed. Review it or use --force.")
        matches.append(index)
if len(matches) != 1:
    raise SystemExit("Expected exactly one Manager exec line; wrapper was not changed. Review it or use --force.")
index = matches[0]
words = shlex.split(lines[index])
if words[3:] in ([mode], ["--mode", mode]):
    print("false")
else:
    backup = path.with_name(path.name + ".mode-backup")
    if not backup.exists():
        shutil.copy2(path, backup)
    lines[index] = f'exec /usr/bin/python3 "$MANAGER_PATH" "{mode}"\n'
    path.write_text("".join(lines))
    print("true")
PYMODE
        )
        if [ "$MODE_CHANGED" = true ]; then
            echo "[INFO] Existing startup mode updated to: $SYSTEM_MODE"
            SOURCE_CHANGED=true
        fi
    fi
    echo "[INFO] $SERVICE_NAME already exists; service registration skipped."
    if [ "$SOURCE_CHANGED" = true ]; then
        echo "[INFO] Manager sources changed; restarting existing service..."
        systemctl restart "$SERVICE_NAME"
    else
        echo "[INFO] Manager sources are unchanged; service left running."
    fi
    echo "[INFO] Select crane/general explicitly to update the mode; --force also replaces the service unit."
    exit 0
fi

# ------------------------------------------------------------
# Create runtime wrapper
#
# This wrapper runs as root from systemd. Root is retained because the existing
# manager can invoke Docker/shutdown and CX128S2 raw Ethernet needs CAP_NET_RAW.
# It waits briefly for the GUI/Xauthority session and then
# launches guardian_manager.py with the GUI environment.
# ------------------------------------------------------------

echo "[INFO] Creating startup wrapper..."

cat > "$START_WRAPPER" <<EOF
#!/usr/bin/env bash
set -euo pipefail

TARGET_USER="${TARGET_USER}"
TARGET_UID="${TARGET_UID}"

DISPLAY_VALUE="${DISPLAY_VALUE}"
XDG_RUNTIME_DIR_VALUE="${XDG_RUNTIME_DIR_VALUE}"
XAUTHORITY_VALUE="${XAUTHORITY_VALUE}"

MANAGER_PATH="${MANAGER_PATH}"

echo "[GUI] Waiting for desktop session..."

# Wait up to roughly 60 seconds for GUI authorization file.
for _ in \$(seq 1 60); do
    if [ -f "\$XAUTHORITY_VALUE" ]; then
        break
    fi

    sleep 1
done

if [ ! -f "\$XAUTHORITY_VALUE" ]; then
    echo "[WARN] XAUTHORITY does not exist:"
    echo "       \$XAUTHORITY_VALUE"
    echo "[WARN] GUI applications such as RViz may not open."
else
    echo "[GUI] XAUTHORITY found:"
    echo "      \$XAUTHORITY_VALUE"

    # Allow root applications to access the logged-in user's X display.
    runuser -u "\$TARGET_USER" -- \
        env \
        DISPLAY="\$DISPLAY_VALUE" \
        XAUTHORITY="\$XAUTHORITY_VALUE" \
        xhost +SI:localuser:root >/dev/null 2>&1 || true
fi

export DISPLAY="\$DISPLAY_VALUE"
export XAUTHORITY="\$XAUTHORITY_VALUE"
export XDG_RUNTIME_DIR="\$XDG_RUNTIME_DIR_VALUE"

echo "[GUI] DISPLAY=\$DISPLAY"
echo "[GUI] XAUTHORITY=\$XAUTHORITY"
echo "[GUI] XDG_RUNTIME_DIR=\$XDG_RUNTIME_DIR"

echo "[MANAGER] Starting Guardian AI Manager..."

exec /usr/bin/python3 "\$MANAGER_PATH" "${SYSTEM_MODE}"
EOF

chmod 755 "$START_WRAPPER"

# ------------------------------------------------------------
# Remove old service
# ------------------------------------------------------------

if [ "$SERVICE_EXISTS" = true ]; then
    echo "[INFO] Replacing existing service..."
    systemctl stop "$SERVICE_NAME" 2>/dev/null || true
    systemctl disable "$SERVICE_NAME" 2>/dev/null || true
    rm -f "$SERVICE_PATH"
    systemctl daemon-reload
    systemctl reset-failed "$SERVICE_NAME" 2>/dev/null || true
fi

# ------------------------------------------------------------
# Create systemd service
# ------------------------------------------------------------

echo "[INFO] Creating systemd service..."

cat > "$SERVICE_PATH" <<EOF
[Unit]
Description=Guardian AI Manager
Wants=network-online.target
After=network-online.target docker.service

[Service]
Type=simple
User=root

Environment=DISPLAY=${DISPLAY_VALUE}
Environment=XAUTHORITY=${XAUTHORITY_VALUE}
Environment=XDG_RUNTIME_DIR=${XDG_RUNTIME_DIR_VALUE}

WorkingDirectory=${WORK_DIR}
ExecStart=${START_WRAPPER}

[Install]
WantedBy=multi-user.target
EOF

chmod 644 "$SERVICE_PATH"

# ------------------------------------------------------------
# systemd reload
# ------------------------------------------------------------

echo "[INFO] Reloading systemd..."

systemctl daemon-reload

# ------------------------------------------------------------
# Enable at boot
# ------------------------------------------------------------

echo "[INFO] Enabling service..."

systemctl enable "$SERVICE_NAME"

# ------------------------------------------------------------
# Try X11 permission now if desktop session is available
# ------------------------------------------------------------

if [ -f "$XAUTHORITY_VALUE" ]; then
    echo "[INFO] Desktop Xauthority detected."

    runuser -u "$TARGET_USER" -- \
        env \
        DISPLAY="$DISPLAY_VALUE" \
        XAUTHORITY="$XAUTHORITY_VALUE" \
        xhost +SI:localuser:root >/dev/null 2>&1 || {
            echo "[WARN] Could not add root to X11 access control."
            echo "[WARN] Startup wrapper will try again."
        }
else
    echo "[WARN] Desktop Xauthority is not currently available."
    echo "[WARN] Expected:"
    echo "       $XAUTHORITY_VALUE"
    echo "[WARN] This can be normal before GUI login."
fi

# ------------------------------------------------------------
# Start service
# ------------------------------------------------------------

echo
echo "[INFO] Starting Guardian AI Manager..."

systemctl restart "$SERVICE_NAME"

# ------------------------------------------------------------
# Result
# ------------------------------------------------------------

echo
echo "============================================================"
echo " Guardian AI Manager installation complete"
echo "============================================================"
echo

systemctl --no-pager --full status "$SERVICE_NAME" || true

echo
echo "------------------------------------------------------------"
echo " Useful commands"
echo "------------------------------------------------------------"
echo
echo "Status:"
echo "  sudo systemctl status ${SERVICE_NAME}"
echo
echo "Restart:"
echo "  sudo systemctl restart ${SERVICE_NAME}"
echo
echo "Stop:"
echo "  sudo systemctl stop ${SERVICE_NAME}"
echo
echo "Live logs:"
echo "  journalctl -u ${SERVICE_NAME} -f"
echo
echo "Last 100 log lines:"
echo "  journalctl -u ${SERVICE_NAME} -n 100 --no-pager"
echo
echo "Runtime manager:"
echo "  ${MANAGER_PATH}"
echo
echo "Service file:"
echo "  ${SERVICE_PATH}"
echo
echo "IMPORTANT:"
echo "  run_lidar.sh must NOT use:"
echo
echo "      docker exec -it"
echo
echo "  For automatic systemd startup use:"
echo
echo "      docker exec -d"
echo
